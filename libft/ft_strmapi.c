#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	int		i;
	int		m;
	char	*result;

	if (!s || !f)
		return (NULL);
	m = ft_strlen(s);
	i = 0;
	result = (char *)malloc((m + 1) * sizeof(char));
	if (!result)
		return (NULL);
	while (s[i])
	{
		result[i] = f(i, s[i]);
		i++;
	}
	result[i] = '\0';
	return (result);
}
